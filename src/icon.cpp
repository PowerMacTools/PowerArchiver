void setup_pixmap_table(MwWidget handle) {
  for (auto &[file, mime_types] : icon_files) {
    std::string path = fs::join(MARCHIVER_ICON_DIR, file);
    MwPixmap pixmap = MwLoadImage(handle, path.c_str());

    for (auto &mime_type : mime_types)
      icon_map[mime_type] = pixmap;
  }
};

MwPixmap get_pixmap_from_mime_type(const char *mime_type) {
  auto it = icon_map.find(mime_type);

  if (it == icon_map.end())
    it = icon_map.find("application/octet-stream");
  return it->second;
};
